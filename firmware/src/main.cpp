void onWiFiEvent(arduino_event_id_t event, arduino_event_info_t info) {
  switch (event) {
    case ARDUINO_EVENT_WIFI_STA_GOT_IP:
      connectCount++;
      failStreak = 0;
      lastError = "";
      Serial.printf("[wifi] CONNECTED  IP %s  signal %d dBm  channel %d  tx %s dBm\n",
                    WiFi.localIP().toString().c_str(), WiFi.RSSI(), WiFi.channel(), TX_LABEL[txInUse]);
      break;
    case ARDUINO_EVENT_WIFI_STA_DISCONNECTED: {
      uint8_t r = info.wifi_sta_disconnected.reason;
      lastReason = r; discCount++; failStreak++;
      Serial.printf("[wifi] disconnected: reason %d = %s (tx %s dBm)\n", r, reasonName(r), TX_LABEL[txInUse]);
      if (r == WIFI_REASON_NO_AP_FOUND) lastError = "(router not heard)";
      else if (r == WIFI_REASON_AUTH_FAIL) lastError = "(wrong password?)";
      else if (r == WIFI_REASON_HANDSHAKE_TIMEOUT || r == WIFI_REASON_4WAY_HANDSHAKE_TIMEOUT)
        lastError = "(weak signal or wrong password)";
      else lastError = "(signal lost)";
      break;
    }
    case ARDUINO_EVENT_WIFI_AP_STACONNECTED:
      Serial.println("[wifi] a device joined the hotspot");
      break;
    default: break;
  }
}

void manageWifi() {
  uint32_t now = millis();
  bool connected = WiFi.status() == WL_CONNECTED;

  if (connected) {
    if (!wasConnected) { staUpSince = now; wasConnected = true; MDNS.begin(HOST_NAME); }
    if (apOn && WiFi.softAPgetStationNum() > 0) staUpSince = now;  // someone is using it: wait
    if (apOn && now - staUpSince > AP_OFF_AFTER_MS) stopAp();
  } else {
    if (wasConnected) { wasConnected = false; staDownSince = now; }
    if (netCount > 0) {
      if (now - lastStaTry > STA_RETRY_MS) {
        if (cfg.tx == TX_AUTO) autoIdx = (autoIdx + 1) % AUTO_STEPS;   // try the next power level
        beginSta();
      }
      // With a saved network the hotspot stays off so the radio can focus on the router.
      // (Use the Bluetooth command "hotspot" to open it again for setup.)
      if (apOn && (int32_t)(now - apUntil) > 0) stopAp();
    } else {
      startAp();
    }
  }
}

