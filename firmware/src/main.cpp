// ---------- network ping test (serial: "ping" = router, "ping 192.168.0.114" = that address) ----------
static volatile int pingOk = 0, pingBad = 0;
static volatile bool pingDone = false;

void pingTarget(IPAddress ip, int count = 5) {
  Serial.printf("[ping] %s x%d ...\n", ip.toString().c_str(), count);
  pingOk = 0; pingBad = 0; pingDone = false;
  esp_ping_config_t pc = ESP_PING_DEFAULT_CONFIG();
  ip_addr_t t; IP_ADDR4(&t, ip[0], ip[1], ip[2], ip[3]);
  pc.target_addr = t; pc.count = count; pc.interval_ms = 500; pc.timeout_ms = 1500;
  esp_ping_callbacks_t cb = {};
  cb.on_ping_success = [](esp_ping_handle_t, void*) { pingOk++; };
  cb.on_ping_timeout = [](esp_ping_handle_t, void*) { pingBad++; };
  cb.on_ping_end     = [](esp_ping_handle_t, void*) { pingDone = true; };
  esp_ping_handle_t h;
  if (esp_ping_new_session(&pc, &cb, &h) != ESP_OK) { Serial.println("[ping] could not start"); return; }
  esp_ping_start(h);
  uint32_t t0 = millis();
  while (!pingDone && millis() - t0 < 15000) delay(50);
  esp_ping_stop(h);
  esp_ping_delete_session(h);
  Serial.printf("[ping] %s: %d replies, %d timeouts\n", ip.toString().c_str(), (int)pingOk, (int)pingBad);
}

void handleSerial() {
  static String line;
  while (Serial.available()) {
    char c = Serial.read();
    if (line.isEmpty() && c == 'd') { printDiag(Serial); continue; }
    if (line.isEmpty() && c == '?') { Serial.println("d = diagnostics, s = scan, ping [ip], set <key> <value>"); continue; }
    if (c == '\n' || c == '\r') {
      line.trim();
      if (line == "s" || line == "scan") {
        printScan(Serial);
      } else if (line == "pin") {                          // read the LED data pin level while idle
        REG_SET_BIT(GPIO_PIN_MUX_REG[LED_PIN], FUN_IE);
        int hi = 0;
        for (int n = 0; n < 200; n++) { hi += gpio_get_level((gpio_num_t)LED_PIN); delayMicroseconds(50); }
        Serial.printf("[pin] GPIO %d idle: high in %d of 200 samples\n", LED_PIN, hi);
      } else if (line == "pattern") {
        rawIndex = -2; rawMode = true;
        Serial.println("[usb] pattern: LED1 red, LED2 green, LED3 blue, LED4 white");
      } else if (line.startsWith("raw")) {                 // raw R G B W [index]
        int r = 0, g = 0, b = 0, w = 0, idx = -1;
        int n = sscanf(line.c_str(), "raw %d %d %d %d %d", &r, &g, &b, &w, &idx);
        if (n >= 4) {
          rawVal[0] = r; rawVal[1] = g; rawVal[2] = b; rawVal[3] = w; rawIndex = n >= 5 ? idx : -1; rawMode = true;
          Serial.printf("[usb] raw R%d G%d B%d W%d on %s\n", r, g, b, w, rawIndex < 0 ? "all LEDs" : ("LED " + String(rawIndex)).c_str());
        } else Serial.println("[usb] usage: raw R G B W [led index 0-3]");
      } else if (line.startsWith("set ")) {                      // USB: "set on 1", "set mode moon", "set ble 1" ...
        String rest = line.substring(4); rest.trim();
        int sp = rest.indexOf(' ');
        bool ok = applySetting(sp < 0 ? rest : rest.substring(0, sp), sp < 0 ? String("") : rest.substring(sp + 1));
        Serial.printf("[usb] \"%s\" -> %s\n", rest.c_str(), ok ? "ok" : "unknown");
      } else if (line.startsWith("ping")) {
        String arg = line.substring(4); arg.trim();
        IPAddress ip;
        if (arg.isEmpty()) ip = WiFi.gatewayIP();
        if (arg.isEmpty() || ip.fromString(arg)) pingTarget(ip);
        else Serial.println("[ping] usage: ping [ip]");
      }
      line = "";
    } else if (line.length() < 40) line += c;
  }
}

// ---------- Arduino entry points ----------
void setup() {
  Serial.begin(115200);
  delay(300);
  Serial.printf("\nMoonPixel starting (last reset: %s)\n", resetName());

  loadSettings();
  bool ledOk = leds.begin(LED_PIN, LED_COUNT, isRgbw() ? 4 : 3);
  leds.setRgbFirst(cfg.ledt == 1 || cfg.ledt == 3);
  Serial.printf("[led] driver %s\n", ledOk ? "ready" : "FAILED");
  leds.clear();
  leds.show(true);

  if (cfg.ble) setupBle();              // Bluetooth first: the C3 aborts if it starts after Wi-Fi

  WiFi.persistent(false);               // we keep our own saved settings; don't wear flash
  WiFi.setAutoReconnect(true);
  WiFi.onEvent(onWiFiEvent);
  WiFi.mode(WIFI_STA);                  // hotspot only if there is no saved network (see below)
  WiFi.setHostname(HOST_NAME);
  WiFi.setScanMethod(WIFI_ALL_CHANNEL_SCAN);          // look at every channel...
  WiFi.setSortMethod(WIFI_CONNECT_AP_BY_SIGNAL);      // ...and join the strongest router with that name
  WiFi.setMinSecurity(WIFI_AUTH_WPA_PSK);             // don't reject older WPA/WPA2 mixed routers
  applyRadioSettings();
  if (netCount == 0) startAp();         // first-time setup: open the hotspot
  beginSta();

  setupRoutes();
  server.begin();
  Serial.printf("[web] ready. %u saved network(s). Send 'd' over serial for diagnostics.\n", netCount);
  ledDirty = true;
}

void loop() {
  server.handleClient();
  handlePending();
  manageWifi();
  renderLeds();
  handleSerial();

  // Save settings 3 s after the last change (a flash write mid-drag is avoided).
  if (settingsDirty && millis() - settingsDirtyAt > 3000) { saveLedSettings(); settingsDirty = false; }

  static uint32_t lastLog = 0;
  if (millis() - lastLog > 10000) {
    lastLog = millis();
    if (WiFi.status() == WL_CONNECTED)
      Serial.printf("[status] online %s  %d dBm  tx %s  heap %u\n", WiFi.localIP().toString().c_str(),
                    WiFi.RSSI(), TX_LABEL[txInUse], ESP.getFreeHeap());
    else
      Serial.printf("[status] offline, hotspot %s, tx %s, fails %u, heap %u\n", apOn ? "on" : "off",
                    TX_LABEL[txInUse], failStreak, ESP.getFreeHeap());
  }
  delay(2);
}
