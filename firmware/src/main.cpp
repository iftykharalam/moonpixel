    case WIFI_REASON_BEACON_TIMEOUT:            return "BEACON_TIMEOUT (lost signal)";
    case WIFI_REASON_NO_AP_FOUND:               return "NO_AP_FOUND (can't hear router)";
    case WIFI_REASON_AUTH_FAIL:                 return "AUTH_FAIL (wrong password?)";
    case WIFI_REASON_ASSOC_FAIL:                return "ASSOC_FAIL";
    case WIFI_REASON_HANDSHAKE_TIMEOUT:         return "HANDSHAKE_TIMEOUT (weak link / wrong password)";
    case WIFI_REASON_4WAY_HANDSHAKE_TIMEOUT:    return "4WAY_HANDSHAKE_TIMEOUT (weak link / wrong password)";
    case WIFI_REASON_CONNECTION_FAIL:           return "CONNECTION_FAIL";
