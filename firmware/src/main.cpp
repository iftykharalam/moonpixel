// ---------- one place that changes a setting (used by the web page AND Bluetooth) ----------
bool applySetting(String k, String v) {
  rawMode = false;                      // any normal setting ends the raw test
  k.trim(); k.toLowerCase(); v.trim(); v.toLowerCase();
  if (k == "on" || k == "off" || k == "toggle") {
    if (k == "toggle") cfg.on = !cfg.on;
    else if (k == "off") cfg.on = false;
    else cfg.on = v.isEmpty() ? true : (v != "0" && v != "off" && v != "false");
  } else if (k == "mode") {
    int m = -1;
    for (uint8_t i = 0; i < MODE_COUNT; i++) if (v == MODE_NAME[i]) m = i;
    cfg.mode = m >= 0 ? m : constrain(v.toInt(), 0, MODE_COUNT - 1);
  } else if (k == "bri") {
    cfg.bri = constrain(v.toInt(), 1, 255);
  } else if (k == "spd") {
    cfg.spd = constrain(v.toInt(), 1, 10);
  } else if (k == "color") {
    if (v.startsWith("#")) v.remove(0, 1);
    cfg.color = strtoul(v.c_str(), nullptr, 16) & 0xFFFFFF;
  } else if (k == "range") {
    bool want = !(v == "0" || v == "off" || v == "false");
    if (want != cfg.lr) { cfg.lr = want; saveLedSettings(); pendingAction = 4; }   // restart to apply
  } else if (k == "ble") {
    bool want = !(v == "0" || v == "off" || v == "false");
    if (want != cfg.ble) { cfg.ble = want; saveLedSettings(); pendingAction = 4; }   // restart to apply
  } else if (k == "tx") {
    cfg.tx = constrain(v.toInt(), 0, TX_AUTO);
    applyRadioSettings();
    Serial.printf("[wifi] TX power setting: %s -> using %s dBm\n",
                  cfg.tx == TX_AUTO ? "Auto" : TX_LABEL[cfg.tx], TX_LABEL[txInUse]);
  } else {
    return false;
  }
  ledDirty = true;
  settingsDirty = true; settingsDirtyAt = millis();   // saved a few seconds later (see loop)
  return true;
}

// ---------- Bluetooth LE control ----------
// Works with any BLE app that can write text, e.g. "nRF Connect" or "LightBlue".
//   Service  4d4f4f4e-5049-5845-4c00-000000000001
//   Command  ...0002  (write text):  on | off | toggle | mode rainbow | mode 2 | color FF8800
//                                    bri 120 | spd 3          (several at once: "on; mode 1; color 00FF00")
//   Status   ...0003  (read / notify): current settings as text
#define BLE_SERVICE_UUID "4d4f4f4e-5049-5845-4c00-000000000001"
#define BLE_CMD_UUID     "4d4f4f4e-5049-5845-4c00-000000000002"
#define BLE_STATE_UUID   "4d4f4f4e-5049-5845-4c00-000000000003"

NimBLECharacteristic* bleState = nullptr;
volatile uint8_t bleClients = 0;

String bleStatusText() {
  char col[8]; snprintf(col, sizeof col, "%06X", (unsigned)(cfg.color & 0xFFFFFF));
  String s = "on=" + String(cfg.on ? 1 : 0) + " mode=" + String(cfg.mode) + " color=" + col +
             " bri=" + String(cfg.bri) + " spd=" + String(cfg.spd) + " wifi=";
  s += WiFi.status() == WL_CONNECTED ? WiFi.localIP().toString() + " " + String(WiFi.RSSI()) + "dBm" : String("offline");
  return s;
}

void bleNotify() {
  if (!bleState) return;
  bleState->setValue(bleStatusText().c_str());
  if (bleClients) bleState->notify();
}

class BleCmdCallbacks : public NimBLECharacteristicCallbacks {
  void onWrite(NimBLECharacteristic* c) override {
    String all = String(c->getValue().c_str());
    String lower = all; lower.trim(); lower.toLowerCase();
    if (lower.startsWith("wifi")) {                      // wifi MyNetwork|MyPassword   (whole line, no ; splitting)
      String rest = all; rest.trim(); rest.remove(0, 4);
      while (rest.length() && (rest[0] == ' ' || rest[0] == '=' || rest[0] == ':')) rest.remove(0, 1);
      int bar = rest.indexOf('|');
      pendSsid = bar < 0 ? rest : rest.substring(0, bar);
      pendPass = bar < 0 ? String("") : rest.substring(bar + 1);
      Serial.printf("[ble] wifi command for \"%s\" (password not shown)\n", pendSsid.c_str());
      pendingAction = 1;
      return;
    }
    if (lower == "forget" || lower == "hotspot" || lower == "reboot") {
      if (lower == "forget") pendSsid = "";            // over Bluetooth: forget all saved networks
      pendingAction = lower == "forget" ? 2 : lower == "hotspot" ? 3 : 4;
      Serial.printf("[ble] \"%s\" -> ok\n", lower.c_str());
      return;
    }
    int start = 0;
    while (start <= (int)all.length()) {                 // commands separated by ; or newline
      int end = start;
      while (end < (int)all.length() && all[end] != ';' && all[end] != '\n') end++;
      String one = all.substring(start, end);
      one.trim();
      if (one.length()) {
        int sp = 0;
        while (sp < (int)one.length() && one[sp] != ' ' && one[sp] != '=' && one[sp] != ':') sp++;
        bool ok = applySetting(one.substring(0, sp), sp < (int)one.length() ? one.substring(sp + 1) : String(""));
        Serial.printf("[ble] \"%s\" -> %s\n", one.c_str(), ok ? "ok" : "unknown command");
      }
      start = end + 1;
    }
    bleNotify();
  }
};

class BleServerCallbacks : public NimBLEServerCallbacks {
  void onConnect(NimBLEServer*) override { bleClients++; Serial.println("[ble] phone connected"); }
  void onDisconnect(NimBLEServer*) override {
    if (bleClients) bleClients--;
    Serial.println("[ble] phone disconnected");
    NimBLEDevice::startAdvertising();
  }
};

void setupBle() {
  NimBLEDevice::init("MoonPixel");
  NimBLEDevice::setPower(ESP_PWR_LVL_P3);
  NimBLEServer* srv = NimBLEDevice::createServer();
  srv->setCallbacks(new BleServerCallbacks());
  NimBLEService* svc = srv->createService(BLE_SERVICE_UUID);
  NimBLECharacteristic* cmd = svc->createCharacteristic(
      BLE_CMD_UUID, NIMBLE_PROPERTY::WRITE | NIMBLE_PROPERTY::WRITE_NR);
  cmd->setCallbacks(new BleCmdCallbacks());
  bleState = svc->createCharacteristic(
      BLE_STATE_UUID, NIMBLE_PROPERTY::READ | NIMBLE_PROPERTY::NOTIFY);
  bleState->setValue(bleStatusText().c_str());
  svc->start();
  NimBLEAdvertising* adv = NimBLEDevice::getAdvertising();
  adv->addServiceUUID(BLE_SERVICE_UUID);
  adv->setScanResponse(true);
  adv->setMinInterval(400);   // 250 ms: gentle on the radio shared with Wi-Fi
  adv->setMaxInterval(800);   // 500 ms
  adv->start();
  Serial.println("[ble] advertising as \"MoonPixel\"");
}

