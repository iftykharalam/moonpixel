# Runs before every build (see platformio.ini). Compresses the control page in src/web_page.h
# into src/web_page_gz.h so the lamp sends ~2 KB instead of ~7 KB: far fewer packets to lose on a
# weak Wi-Fi link. Edit the page in src/web_page.h; this file is regenerated automatically.
import gzip, re, pathlib
try:
    Import("env")  # noqa: F821  (PlatformIO/SCons)
    root = pathlib.Path(env["PROJECT_DIR"])  # noqa: F821
except Exception:
    root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "src" / "web_page.h").read_text()
m = re.search(r'R"HTML\((.*)\)HTML"', src, re.S)
assert m, "page markers not found in web_page.h"
html = re.sub(r">\s+<", "><", m.group(1)).encode("utf-8")   # light minify
gz = gzip.compress(html, 9, mtime=0)
rows = [", ".join(f"0x{b:02x}" for b in gz[i:i + 16]) for i in range(0, len(gz), 16)]
out = ("// GENERATED by tools/gen_web.py from web_page.h - do not edit.\n#pragma once\n#include <Arduino.h>\n"
       f"static const uint8_t INDEX_HTML_GZ[] PROGMEM = {{\n  " + ",\n  ".join(rows) + "\n};\n"
       f"static const size_t INDEX_HTML_GZ_LEN = {len(gz)};\n")
(root / "src" / "web_page_gz.h").write_text(out)
print(f"[gen_web] page {len(m.group(1))} bytes -> {len(gz)} bytes gzip")
